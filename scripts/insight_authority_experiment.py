def build_plans(
    packets: list[AuthorityPacket],
    *,
    validation: dict[str, Any],
    schedule: dict[str, datetime],
    config: CadenceConfig,
    out_dir: Path,
    privacy: str,
    render_thumbnails: bool,
    dry_run: bool,
    youtube_mutations: bool = False,
) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    validation_by_slug = {item["slug"]: item for item in validation["items"]}
    emit_items: list[dict[str, Any]] = []
    publish_items: list[dict[str, Any]] = []
    combined_items: list[dict[str, Any]] = []
    for packet in packets:
        metadata = render_metadata(packet)
        thumbnail_path = out_dir / "thumbnails" / f"{packet.slug}.png"
        ok = validation_by_slug.get(packet.slug, {}).get("ok", False)
        comment_text = render_technical_comment(packet)
        is_repair = is_repair_packet(packet)
        cadence_class = "research_snapshot_short" if is_research_snapshot_short(packet) else "longform"
        scheduled_at = schedule.get(packet.slug)
        mutation = "none"
        if is_repair and ok:
            mutation = "youtube_apply" if youtube_mutations and ok else "metadata_only"
        emit_item = {
            "slug": packet.slug,
            "status": "ready" if ok else "blocked",
            "youtube_video_id": packet.youtube_video_id,
            "package": packet.package,
            "content_format": packet.content_format,
            "metadata": metadata,
            "thumbnail": {
                "text": " ".join(thumbnail_words(packet.thumbnail_text)),
                "word_count": len(thumbnail_words(packet.thumbnail_text)),
                "path": str(thumbnail_path),
                "will_write": bool(render_thumbnails and ok and not dry_run),
            },
        }
        publish_item = {
            "slug": packet.slug,
            "status": "ready" if ok else "blocked",
            "youtube_video_id": packet.youtube_video_id,
            "package": packet.package,
            "content_format": packet.content_format,
            "cadence_class": cadence_class,
            "allowed_weekdays": weekday_names(cadence_weekdays_for(packet, config)),
            "scheduled_at": scheduled_at.isoformat().replace("+00:00", "Z") if ok and scheduled_at else None,
            "privacy": privacy,
            "mutation": mutation,
            "metadata_ref": metadata,
            "thumbnail_path": str(thumbnail_path) if render_thumbnails else None,
            "source_url": packet.source_url,
            "research_breakdown_url": packet.research_breakdown_url,
            "comment": {
                "will_post": bool(comment_text and youtube_mutations and ok),
                "pin_status": PIN_STATUS_BLOCKED if comment_text and youtube_mutations and ok else "not_requested",
            },
        }
        emit_items.append(emit_item)
        publish_items.append(publish_item)
        combined_items.append(
            {
                "slug": packet.slug,
                "ok": ok,
                "issues": validation_by_slug.get(packet.slug, {}).get("issues", []),
                "emit": emit_item,
                "publish": publish_item,
            }
        )

    emit_plan = {"workflow": "insight_authority_emit", "dry_run": dry_run, "items": emit_items}
    publish_plan = {
        "workflow": "insight_authority_publish_plan",
        "dry_run": dry_run,
        "youtube_mutations": youtube_mutations,
        "items": publish_items,
    }
    combined_plan = {
        "workflow": "insight_authority_experiment",
        "created_at": now_utc().isoformat(),
        "dry_run": dry_run,
        "youtube_mutations": youtube_mutations,
        "validation": validation,
        "items": combined_items,
    }
    return combined_plan, emit_plan, publish_plan


