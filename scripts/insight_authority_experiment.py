def parse_iso_datetime(value: str) -> datetime:
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ValueError(f"invalid ISO datetime: {value}") from exc
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def now_utc() -> datetime:
    return datetime.now(timezone.utc)


def load_data(path: Path) -> Any:
    raw = path.read_text(encoding="utf-8")
    if path.suffix.lower() in {".yaml", ".yml"}:
        return yaml.safe_load(raw)
    return json.loads(raw)


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def load_packet_entries(path: Path) -> list[dict[str, Any]]:
    data = load_data(path)
    if isinstance(data, list):
        entries = data
    elif isinstance(data, dict):
        if isinstance(data.get("packets"), list):
            entries = data["packets"]
        elif isinstance(data.get("items"), list):
            entries = data["items"]
        elif isinstance(data.get("entries"), list):
            entries = data["entries"]
        elif any(field in data for field in REQUIRED_PACKET_FIELDS):
            entries = [data]
        else:
            entries = []
    else:
        entries = []
    return [entry for entry in entries if isinstance(entry, dict)]


def words(value: str | None) -> list[str]:
    return WORD_RE.findall(value or "")


def compact_whitespace(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def strip_wrapper_suffixes(value: str) -> str:
    cleaned = compact_whitespace(value)
    changed = True
    while changed:
        changed = False
        for pattern in WRAPPER_SUFFIX_PATTERNS:
            updated = pattern.sub("", cleaned).strip()
            if updated != cleaned:
                cleaned = updated
                changed = True
    return cleaned.strip(" -|")


def strip_wrapper_openers(value: str) -> str:
    cleaned = compact_whitespace(value)
    opener_patterns = (
        re.compile(r"^in this video,?\s*", re.IGNORECASE),
        re.compile(r"^this video (?:explores|explains|shows|breaks down)\s*", re.IGNORECASE),
        re.compile(r"^this cinematic (?:research )?brief\s*", re.IGNORECASE),
        re.compile(r"^welcome to\s*", re.IGNORECASE),
        re.compile(r"^let'?s dive into\s*", re.IGNORECASE),
    )
    for pattern in opener_patterns:
        cleaned = pattern.sub("", cleaned).strip()
    return cleaned


def remove_forbidden_wrapper_phrases(value: str) -> str:
    cleaned = value
    replacements = {
        "AI-generated": "",
        "ai-generated": "",
        "generated by AI": "",
        "Generated by AI": "",
        "TL;DR": "",
        "tl;dr": "",
    }
    for needle, replacement in replacements.items():
        cleaned = cleaned.replace(needle, replacement)
    return compact_whitespace(cleaned)


def plain_language(value: str) -> str:
    cleaned = strip_wrapper_openers(strip_wrapper_suffixes(remove_forbidden_wrapper_phrases(value)))
    for pattern, replacement in JARGON_REPLACEMENTS:
        cleaned = pattern.sub(replacement, cleaned)
    cleaned = re.sub(r"\s+([,.;:!?])", r"\1", cleaned)
    cleaned = re.sub(r"([.!?]){2,}", r"\1", cleaned)
    return compact_whitespace(cleaned)


def normalize_title(value: str) -> str:
    cleaned = plain_language(value)
    return cleaned[:1].upper() + cleaned[1:] if cleaned else cleaned


def evidence_list(value: Any) -> list[str]:
    if isinstance(value, list):
        return [compact_whitespace(str(item)) for item in value if compact_whitespace(str(item))]
    if isinstance(value, dict):
        return [
            f"{key}: {item}"
            for key, item in value.items()
            if compact_whitespace(str(item)) and str(item).lower() not in {"none", "null"}
        ]
    if value in (None, ""):
        return []
    return [compact_whitespace(str(value))]


def tag_list(value: Any) -> list[str]:
    if not isinstance(value, list):
        return []
    result: list[str] = []
    for item in value:
        tag = re.sub(r"[^a-z0-9-]", "", plain_language(str(item)).lower().replace(" ", "-"))
        if tag and tag not in result and tag not in FORBIDDEN_JARGON:
            result.append(tag)
    return result


def optional_text(value: Any) -> str | None:
    cleaned = compact_whitespace(str(value or ""))
    return cleaned or None


def normalized_format(value: Any) -> str | None:
    cleaned = compact_whitespace(str(value or "")).lower()
    if not cleaned:
        return None
    return re.sub(r"[^a-z0-9]+", "_", cleaned).strip("_") or None


def youtube_video_id_from(value: Any) -> str | None:
    cleaned = compact_whitespace(str(value or ""))
    if not cleaned:
        return None
    if re.fullmatch(r"[A-Za-z0-9_-]{6,}", cleaned):
        return cleaned
    patterns = (
        re.compile(r"(?:youtube\.com/watch\?[^#\s]*v=)([A-Za-z0-9_-]{6,})"),
        re.compile(r"(?:youtu\.be/)([A-Za-z0-9_-]{6,})"),
        re.compile(r"(?:youtube\.com/embed/)([A-Za-z0-9_-]{6,})"),
    )
    for pattern in patterns:
        match = pattern.search(cleaned)
        if match:
            return match.group(1)
    return None


def coerce_packet(raw: dict[str, Any]) -> AuthorityPacket:
    publish_at = raw.get("publish_at") or raw.get("scheduled_at")
    parsed_publish_at = parse_iso_datetime(str(publish_at)) if publish_at else None
    linked_sources = raw.get("linked_sources") if isinstance(raw.get("linked_sources"), dict) else {}
    youtube_video_id = youtube_video_id_from(
        raw.get("youtube_video_id") or raw.get("video_id") or raw.get("youtube_url")
    )
    return AuthorityPacket(
        slug=compact_whitespace(str(raw.get("slug") or "")),
        youtube_video_id=youtube_video_id,
        package=optional_text(raw.get("package") or raw.get("publication_package") or raw.get("publication")),
        title=compact_whitespace(str(raw.get("title") or "")),
        claim=compact_whitespace(str(raw.get("claim") or raw.get("insight_authority_angle") or "")),
        evidence=evidence_list(raw.get("evidence") or raw.get("proof") or raw.get("local_evidence")),
        thumbnail_text=compact_whitespace(str(raw.get("thumbnail_text") or raw.get("thumbnail") or "")),
        source_url=compact_whitespace(
            str(raw.get("source_url") or raw.get("url") or linked_sources.get("essay_url") or raw.get("youtube_url") or "")
        )
        or None,
        research_breakdown_url=optional_text(
            raw.get("research_breakdown_url")
            or raw.get("full_research_breakdown_url")
            or linked_sources.get("research_breakdown_url")
        ),
        description=compact_whitespace(
            str(raw.get("description") or raw.get("summary") or raw.get("selection_rationale") or "")
        )
        or None,
        author_note=optional_text(raw.get("author_note")),
        technical_dilemma=optional_text(raw.get("technical_dilemma")),
        pinned_comment=optional_text(raw.get("pinned_comment")),
        tags=tag_list(raw.get("tags")),
        publish_at=parsed_publish_at,
        content_format=normalized_format(raw.get("content_format") or raw.get("video_format") or raw.get("format")),
        raw=raw,
    )


def render_description(packet: AuthorityPacket) -> str:
    sections: list[str] = []
    lead = plain_language(packet.description or packet.claim)
    if lead:
        sections.append(lead)

    claim = plain_language(packet.claim)
    if claim and (not sections or claim.lower() not in sections[0].lower()):
        sections.append(f"Claim: {claim}")

    evidence = [plain_language(item) for item in packet.evidence if plain_language(item)]
    if evidence:
        sections.append(f"Evidence: {'; '.join(evidence[:3])}")

    if packet.technical_dilemma:
        sections.append(f"Technical dilemma: {plain_language(packet.technical_dilemma)}")
    if packet.author_note:
        sections.append(f"Author note: {plain_language(packet.author_note)}")
    if packet.source_url:
        sections.append(f"Source: {packet.source_url}")
    if packet.research_breakdown_url:
        sections.append(f"Research breakdown: {packet.research_breakdown_url}")

    description = "\n\n".join(section for section in sections if section).strip()
    if len(description) > MAX_YOUTUBE_DESCRIPTION_LENGTH:
        return description[: MAX_YOUTUBE_DESCRIPTION_LENGTH - 3].rstrip() + "..."
    return description


def render_metadata(packet: AuthorityPacket) -> dict[str, Any]:
    title = normalize_title(packet.title)
    description = render_description(packet)
    tags = ["rootedlayers", "research", *packet.tags]
    deduped_tags = list(dict.fromkeys(tag for tag in tags if tag))
    return {
        "title": title,
        "description": description,
        "tags": deduped_tags,
    }


def field_contains_phrase(value: str, phrases: Iterable[str]) -> str | None:
    lowered = value.lower()
    for phrase in phrases:
        if phrase in lowered:
            return phrase
    return None


def field_contains_jargon(value: str) -> str | None:
    lowered_words = {word.lower() for word in words(value)}
    for term in FORBIDDEN_JARGON:
        if term in lowered_words:
            return term
    return None


def description_body(value: str) -> str:
    return "\n".join(
        line
        for line in value.splitlines()
        if not line.lower().startswith(("source:", "research breakdown:"))
    )


def validate_packet(packet: AuthorityPacket) -> list[dict[str, str]]:
    issues: list[dict[str, str]] = []
    if not packet.slug:
        issues.append({"field": "slug", "message": "missing required field"})
    elif not SLUG_RE.match(packet.slug):
        issues.append({"field": "slug", "message": "use lowercase letters, numbers, hyphens, or underscores"})
    if not packet.title:
        issues.append({"field": "title", "message": "missing required field"})
    if not packet.claim:
        issues.append({"field": "claim", "message": "missing required field"})
    if not packet.evidence:
        issues.append({"field": "evidence", "message": "missing required field"})
    if not packet.thumbnail_text:
        issues.append({"field": "thumbnail_text", "message": "missing required field"})
    elif len(words(packet.thumbnail_text)) > DEFAULT_THUMBNAIL_WORD_LIMIT:
        issues.append(
            {
                "field": "thumbnail_text",
                "message": f"thumbnail text must be {DEFAULT_THUMBNAIL_WORD_LIMIT} words or fewer",
            }
        )

    raw_fields = {
        "claim": packet.claim,
        "description": packet.description or "",
    }
    for field, value in raw_fields.items():
        phrase = field_contains_phrase(value, FORBIDDEN_WRAPPERS)
        if phrase:
            issues.append({"field": field, "message": f"forbidden wrapper phrase in packet source: {phrase}"})

    metadata = render_metadata(packet)
    for field in ("title", "description"):
        value = description_body(str(metadata[field])) if field == "description" else str(metadata[field])
        phrase = field_contains_phrase(value, FORBIDDEN_WRAPPERS)
        if phrase:
            issues.append({"field": field, "message": f"forbidden wrapper phrase remains: {phrase}"})
        jargon = field_contains_jargon(value)
        if jargon:
            issues.append({"field": field, "message": f"jargon remains after rendering: {jargon}"})
    return issues


def validate_packets(packets: list[AuthorityPacket]) -> dict[str, Any]:
    if not packets:
        return {
            "ok": False,
            "issue_count": 1,
            "items": [
                {
                    "index": 0,
                    "slug": "packets",
                    "ok": False,
                    "issues": [{"field": "packets", "message": "no authority packets found"}],
                }
            ],
        }

    slug_counts: dict[str, int] = {}
    for packet in packets:
        if packet.slug:
            slug_counts[packet.slug] = slug_counts.get(packet.slug, 0) + 1

    items: list[dict[str, Any]] = []
    for index, packet in enumerate(packets):
        issues = validate_packet(packet)
        if packet.slug and slug_counts.get(packet.slug, 0) > 1:
            issues.append({"field": "slug", "message": f"duplicate slug: {packet.slug}"})
        items.append(
            {
                "index": index,
                "slug": packet.slug or f"packet_{index + 1}",
                "ok": not issues,
                "issues": issues,
            }
        )
    return {
        "ok": all(item["ok"] for item in items),
        "issue_count": sum(len(item["issues"]) for item in items),
        "items": items,
    }


def local_day(value: datetime, tz: ZoneInfo) -> str:
    return value.astimezone(tz).date().isoformat()


def slot_time(value: str) -> time:
    hours, minutes = value.split(":", 1)
    return time(hour=int(hours), minute=int(minutes))


def is_repair_packet(packet: AuthorityPacket) -> bool:
    return bool(packet.youtube_video_id)


def is_research_snapshot_short(packet: AuthorityPacket) -> bool:
    if not packet.content_format:
        return False
    return "short" in packet.content_format or "snapshot" in packet.content_format


def cadence_weekdays_for(packet: AuthorityPacket, config: CadenceConfig) -> tuple[int, ...]:
    if is_research_snapshot_short(packet):
        return config.snapshot_short_weekdays
    return config.longform_weekdays


def weekday_names(values: Iterable[int]) -> list[str]:
    return [WEEKDAY_NAMES[value] for value in values]


def candidate_slots(start_at: datetime, config: CadenceConfig, allowed_weekdays: Iterable[int]) -> Iterable[datetime]:
    tz = ZoneInfo(config.timezone_name)
    slot_values = sorted(slot_time(slot) for slot in config.slot_times)
    allowed = set(allowed_weekdays)
    local_cursor = start_at.astimezone(tz)
    day = local_cursor.date()
    while True:
        if day.weekday() in allowed:
            for slot in slot_values:
                candidate = datetime.combine(day, slot, tzinfo=tz).astimezone(timezone.utc)
                if candidate >= start_at:
                    yield candidate
        day = day + timedelta(days=1)


def cadence_allows(candidate: datetime, scheduled: list[datetime], config: CadenceConfig) -> bool:
    tz = ZoneInfo(config.timezone_name)
    same_day = [item for item in scheduled if local_day(item, tz) == local_day(candidate, tz)]
    if len(same_day) >= config.max_per_day:
        return False
    minimum_delta = timedelta(hours=config.min_hours_between)
    return all(abs(candidate - item) >= minimum_delta for item in scheduled)


def publish_at_allowed(packet: AuthorityPacket, value: datetime, config: CadenceConfig) -> bool:
    tz = ZoneInfo(config.timezone_name)
    return value.astimezone(tz).weekday() in set(cadence_weekdays_for(packet, config))


def governed_schedule(
    packets: list[AuthorityPacket],
    *,
    start_at: datetime,
    existing: list[datetime],
    config: CadenceConfig,
) -> dict[str, datetime]:
    scheduled = sorted(existing)
    result: dict[str, datetime] = {}
    cursor = start_at
    minimum_delta = timedelta(hours=config.min_hours_between)
    for packet in packets:
        preferred = packet.publish_at
        if (
            preferred
            and preferred >= cursor
            and publish_at_allowed(packet, preferred, config)
            and cadence_allows(preferred, scheduled, config)
        ):
            chosen = preferred
        else:
            slot_iter = candidate_slots(cursor, config, cadence_weekdays_for(packet, config))
            chosen = next(slot for slot in slot_iter if cadence_allows(slot, scheduled, config))
        result[packet.slug] = chosen
        scheduled.append(chosen)
        scheduled.sort()
        cursor = chosen + minimum_delta
    return result


def collect_datetimes(value: Any) -> list[datetime]:
    found: list[datetime] = []
    if isinstance(value, dict):
        for key, child in value.items():
            if key in {"publish_at", "scheduled_at"} and isinstance(child, str):
                try:
                    found.append(parse_iso_datetime(child))
                except ValueError:
                    pass
            else:
                found.extend(collect_datetimes(child))
    elif isinstance(value, list):
        for child in value:
            found.extend(collect_datetimes(child))
    return found


def load_history(paths: Iterable[Path]) -> list[datetime]:
    values: list[datetime] = []
    for path in paths:
        if path.exists():
            values.extend(collect_datetimes(load_data(path)))
    return values


def thumbnail_words(value: str) -> list[str]:
    return [word.upper() for word in words(value)]


def chunk(kind: bytes, data: bytes) -> bytes:
    return (
        struct.pack(">I", len(data))
        + kind
        + data
        + struct.pack(">I", binascii.crc32(kind + data) & 0xFFFFFFFF)
    )


def encode_png(width: int, height: int, rgb: bytearray) -> bytes:
    rows = []
    stride = width * 3
    for y in range(height):
        rows.append(b"\x00" + bytes(rgb[y * stride : (y + 1) * stride]))
    raw = b"".join(rows)
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def fill_rect(rgb: bytearray, width: int, height: int, x: int, y: int, w: int, h: int, color: tuple[int, int, int]) -> None:
    red, green, blue = color
    x0 = max(0, x)
    y0 = max(0, y)
    x1 = min(width, x + w)
    y1 = min(height, y + h)
    for row in range(y0, y1):
        offset = (row * width + x0) * 3
        for _ in range(x0, x1):
            rgb[offset : offset + 3] = bytes((red, green, blue))
            offset += 3


def glyph_width(text: str, scale: int) -> int:
    width = 0
    for char in text:
        if char == " ":
            width += 3 * scale
        else:
            width += 6 * scale
    return max(0, width - scale)


def draw_text(rgb: bytearray, width: int, height: int, text: str, x: int, y: int, scale: int, color: tuple[int, int, int]) -> None:
    cursor = x
    for char in text:
        if char == " ":
            cursor += 3 * scale
            continue
        glyph = FONT_5X7.get(char, FONT_5X7.get("-"))
        if not glyph:
            cursor += 6 * scale
            continue
        for row_index, row in enumerate(glyph):
            for col_index, bit in enumerate(row):
                if bit == "1":
                    fill_rect(rgb, width, height, cursor + col_index * scale, y + row_index * scale, scale, scale, color)
        cursor += 6 * scale


def render_thumbnail_png(path: Path, text: str, *, width: int = 1280, height: int = 720) -> None:
    word_lines = thumbnail_words(text)
    if not word_lines:
        raise ValueError("thumbnail text is empty")
    if len(word_lines) > DEFAULT_THUMBNAIL_WORD_LIMIT:
        raise ValueError(f"thumbnail text must be {DEFAULT_THUMBNAIL_WORD_LIMIT} words or fewer")

    background = (246, 244, 238)
    ink = (20, 24, 27)
    accent = (192, 52, 40)
    rgb = bytearray(background * (width * height))
    fill_rect(rgb, width, height, 0, 0, width, 18, accent)
    fill_rect(rgb, width, height, 88, 84, 10, height - 168, accent)
    symbol_size = min(width, height) // 2
    symbol_x = (width - symbol_size) // 2
    symbol_y = (height - symbol_size) // 2
    symbol_stroke = 8
    fill_rect(rgb, width, height, symbol_x, symbol_y, symbol_size, symbol_stroke, accent)
    fill_rect(rgb, width, height, symbol_x, symbol_y + symbol_size - symbol_stroke, symbol_size, symbol_stroke, accent)
    fill_rect(rgb, width, height, symbol_x, symbol_y, symbol_stroke, symbol_size, accent)
    fill_rect(rgb, width, height, symbol_x + symbol_size - symbol_stroke, symbol_y, symbol_stroke, symbol_size, accent)

    longest = max(glyph_width(line, 1) for line in word_lines)
    max_text_width = int(width * 0.78)
    max_text_height = int(height * 0.52)
    scale_by_width = max_text_width // max(1, longest)
    scale_by_height = max_text_height // (len(word_lines) * 7 + (len(word_lines) - 1) * 2)
    scale = max(8, min(42, scale_by_width, scale_by_height))
    line_height = 9 * scale
    total_height = len(word_lines) * 7 * scale + (len(word_lines) - 1) * 2 * scale
    y = (height - total_height) // 2
    for line in word_lines:
        line_width = glyph_width(line, scale)
        x = (width - line_width) // 2
        draw_text(rgb, width, height, line, x, y, scale, ink)
        y += line_height

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(encode_png(width, height, rgb))


