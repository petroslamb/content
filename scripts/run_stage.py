#!/usr/bin/env python3
"""
The Stage Runner: Orchestrates publication lifecycle stages.
Usage: .venv/bin/python scripts/run_stage.py --package <name> --stage <stage>
"""

import sys
import argparse
import subprocess
import yaml
import json
from pathlib import Path
from datetime import datetime

# Advisory Auditor (local import)
sys.path.append(str(Path(__file__).parent))
from audit_package import audit_package, print_report

# --- Configuration & Registry ---

STAGES = [
    "paper_intake",
    "research",
    "essay_iteration",
    "notebooklm_artifacts",
    "article_polish",
    "substack_publishing",
    "archive_sync",
    "youtube_production",
    "distribution"
]

# Maps stage names to prerequisite stages
DEPENDENCY_MAP = {
    "substack_publishing": ["article_polish"],
    "youtube_production": ["essay_iteration"],
    "archive_sync": ["substack_publishing"],
    "distribution": ["substack_publishing"]
}

# Maps stage names to command templates
# Variables in {brackets} will be looked up in the package status.yaml config section
STAGE_COMMANDS = {
    "paper_intake": None, # Manual/Skill-based
    "research": None, # Manual/alphaxiv
    "essay_iteration": None, # Manual gate
    "notebooklm_artifacts": None, # Skill-based
    "article_polish": None, # Manual/Check-based
    "substack_publishing": ".venv/bin/python scripts/sync_markdown_post_to_substack.py --publication-url {substack_url} --post-id {substack_post_id} --markdown {markdown_path}",
    "archive_sync": ".venv/bin/python scripts/sync_substack_archive.py",
    "youtube_production": ".venv/bin/python scripts/render_publication_video.py --package {package_name}",
    "distribution": None # Manual/Socials
}

def load_status(package_path: Path):
    status_path = package_path / "status.yaml"
    if not status_path.exists():
        return None
    with open(status_path, "r") as f:
        return yaml.safe_load(f)

def save_status(package_path: Path, data: dict):
    status_path = package_path / "status.yaml"
    with open(status_path, "w") as f:
        yaml.dump(data, f, default_flow_style=False, sort_keys=False)

def log_run(package_name: str, stage: str, success: bool, output: str, cmd: str = None):
    """
    Generates a structured Reviewable Run record in the proofs directory.
    """
    timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    run_id = f"{timestamp}_{package_name}_{stage}"
    run_dir = Path("reviewable-runs/examples/proofs") / run_id
    packet_dir = run_dir / "review-packet"
    packet_dir.mkdir(parents=True, exist_ok=True)
    
    # 1. Task Spec
    task_spec = f"""# Task Spec

## Run Type
Automated Lifecycle Stage: {stage}

## Objective
Execute the '{stage.replace('_', ' ').title()}' stage for the '{package_name}' publication package.

## Success Criteria
- Command exits with code 0
- Status manifest updated to done: true
"""
    (packet_dir / "task-spec.md").write_text(task_spec)
    
    # 2. Execution Trace
    cmd_str = cmd if cmd else "Manual gate approval"
    execution_trace = f"""# Execution Trace

1. Target package: {package_name}
2. Stage: {stage}
3. Command attempted: `{cmd_str}`
4. Execution Timestamp: {timestamp}

## Raw Output Snippet
```
{output[-4000:]}
```
"""
    (packet_dir / "execution-trace.md").write_text(execution_trace)
    
    # 3. Verification Report
    status_str = "SUCCESS" if success else "FAILURE"
    verification_report = f"""# Verification Report

## Outcome
Status: {status_str}

## Details
Stage '{stage}' was processed for package '{package_name}'.
Verification passed: {success}
"""
    (packet_dir / "verification-report.md").write_text(verification_report)
    
    # 4. Summary README
    readme = f"""# Run Record: {run_id}

This is an automated run record generated by the Content Factory Stage Runner.

- **Package**: {package_name}
- **Stage**: {stage}
- **Status**: {status_str}
- **Packet**: [review-packet/](review-packet/)
"""
    (run_dir / "README.md").write_text(readme)
    
    print(f"Reviewable Run recorded to {run_dir}")

def resolve_args(package_name: str, stage: str, status_data: dict, extra_args: dict):
    """
    Looks up values for the command template.
    Order: CLI args -> status.yaml config -> defaults/inferred
    """
    config = status_data.get("config", {})
    package_path = Path("publications") / package_name
    
    # Inferred defaults (lowest priority)
    inferred = {
        "package_name": package_name,
        "markdown_path": str(package_path / f"{package_name.replace('-', '_')}.md")
    }
    
    # Config overrides inferred, CLI overrides config
    resolved = {**inferred, **config, **extra_args}
    return resolved

def main():
    parser = argparse.ArgumentParser(description="Run a publication lifecycle stage.")
    parser.add_argument("--package", required=True, help="Package name (e.g., binding-gap)")
    parser.add_argument("--stage", required=True, choices=STAGES, help="Stage to run")
    parser.add_argument("--strict-deps", action="store_true", help="Enforce dependency checks (default: advisory warnings)")
    parser.add_argument("--force", action="store_true", help="Run even if already marked done")
    
    # Catch-all for extra arguments to pass to templates
    args, unknown = parser.parse_known_args()
    
    # Parse unknown args into a dict
    extra_args = {}
    it = iter(unknown)
    for part in it:
        if part.startswith("--"):
            key = part[2:].replace("-", "_")
            try:
                val = next(it)
                extra_args[key] = val
            except StopIteration:
                extra_args[key] = True

    package_path = Path("publications") / args.package
    status_data = load_status(package_path)
    
    if not status_data:
        print(f"ERROR: No status.yaml found for package '{args.package}'")
        sys.exit(1)

    # 0. Advisory Pre-Flight Audit
    try:
        report = audit_package(args.package)
        print_report(report)
    except Exception as e:
        # Advisory only, do not block
        print(f"\033[93m[WARNING] Pre-flight audit failed to run: {e}\033[0m")

    # 1. Dependency Check (advisory by default)
    if args.stage in DEPENDENCY_MAP:
        for dep in DEPENDENCY_MAP[args.stage]:
            dep_status = status_data["stages"].get(dep, {})
            if not dep_status.get("done"):
                if args.strict_deps:
                    print(f"ERROR: Stage '{args.stage}' depends on '{dep}', which is not done.")
                    print("Remove --strict-deps to proceed with advisory warnings.")
                    sys.exit(1)
                else:
                    print(f"WARNING: Stage '{args.stage}' typically follows '{dep}', which is not done. Proceeding anyway.")

    # 2. Check if already done
    stage_data = status_data["stages"].get(args.stage, {})
    if stage_data.get("done") and not args.force:
        print(f"Stage '{args.stage}' is already marked as DONE. Use --force to rerun.")
        sys.exit(0)

    # 3. Resolve Command
    cmd_template = STAGE_COMMANDS.get(args.stage)
    if not cmd_template:
        # Manual stage or non-automated yet
        print(f"Stage '{args.stage}' is a manual gate. Mark as done? (y/n)")
        if input().lower() == 'y':
            stage_data["done"] = True
            stage_data["last_updated"] = datetime.now().strftime("%Y-%m-%d")
            save_status(package_path, status_data)
            success = True
            output = f"Manual gate '{args.stage}' approved by user."
            print("Status updated.")
        else:
            success = False
            output = f"Manual gate '{args.stage}' rejected by user."
            print("Status not updated.")
        
        log_run(args.package, args.stage, success, output, cmd=None)
        sys.exit(0 if success else 1)

    try:
        resolved_params = resolve_args(args.package, args.stage, status_data, extra_args)
        cmd = cmd_template.format(**resolved_params)
    except KeyError as e:
        print(f"ERROR: Missing required parameter {e} for stage '{args.stage}'")
        print("Provide it via CLI (e.g. --post-id 123) or add it to status.yaml config.")
        sys.exit(1)

    # 4. Execute
    print(f"Executing: {cmd}")
    process = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    
    success = (process.returncode == 0)
    output = process.stdout + "\n" + process.stderr
    
    if success:
        print(f"SUCCESS: Stage '{args.stage}' completed.")
        stage_data["done"] = True
        stage_data["last_updated"] = datetime.now().strftime("%Y-%m-%d")
        save_status(package_path, status_data)
    else:
        print(f"FAILURE: Stage '{args.stage}' failed with exit code {process.returncode}.")
        print(process.stderr)

    # 5. Log
    log_run(args.package, args.stage, success, output, cmd=cmd)
    
    if not success:
        sys.exit(process.returncode)

if __name__ == "__main__":
    main()
